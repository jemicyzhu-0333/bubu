'use strict';

const { uniqueStrings } = require('./registry');

// 桌宠台词:每一条都是手写的一句短话,直接说出来。
//
// 以前这里是“开头 × 主句 × 结尾”三段相乘拼出上千条,拼出来的都是两个分句的散文
// (“刚醒来的大脑前,让我陪你慢慢进入状态,不着急冲刺。”),而且一个池子里手写的
// 短句只占不到一成,所以实际听到的几乎全是拼出来的。现在只留主句本身:短、具体、
// 不催人。要加台词就往对应的池子里加一句,不要再加“开头”和“结尾”。
//
// 写法约定(pet-content 测试会检查其中可检查的部分):
// - 一句话一个意思,不超过 20 个字,一般只有一个分句;
// - 不用 emoji 和颜文字(角色是像素,文字是原生的);
// - 不说“应该”“必须”“加油”,不评价进度,不拿数字催人;
// - 池子里至少 12 条,免得同一句隔几分钟又出现。
function pool(lines) {
  return uniqueStrings(lines);
}


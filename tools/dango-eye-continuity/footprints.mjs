// Generates src/content/companion/dango-eye-footprints.mjs from the raster PNGs.
// Usage: node tools/dango-eye-continuity/footprints.mjs [--check]
// Ink = alpha > 127 and max(r,g,b) < 100 (the visible dark pupil, not the PNG's
// pink body margin). Relative glyph sizes come from the canonical front view so
// expression size differences (wide/surprised) survive per-view perspective.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { DANGO_RASTER as manifest } from '../../assets/companion/dango/raster/dango.raster.mjs';
import { OPEN_EYE_GLYPHS } from '../../src/capabilities/companion/presentation/dango-eye-projection.mjs';

const target = fileURLToPath(new URL('../../src/content/companion/dango-eye-footprints.mjs', import.meta.url));
const round = value => Math.round(value * 10000) / 10000;
async function inkBounds(src) {
  const image = await loadImage(fs.readFileSync(fileURLToPath(new URL(src, manifest.baseUrl))));
  const canvas = createCanvas(image.width, image.height), ctx = canvas.getContext('2d');
  ctx.drawImage(image, 0, 0);
  const pixels = ctx.getImageData(0, 0, image.width, image.height).data;
  let l = image.width, t = image.height, r = -1, b = -1;
  for (let y = 0; y < image.height; y++) for (let x = 0; x < image.width; x++) {
    const i = (y * image.width + x) * 4;
    if (pixels[i + 3] > 127 && Math.max(pixels[i], pixels[i + 1], pixels[i + 2]) < 100) {
      l = Math.min(l, x); t = Math.min(t, y); r = Math.max(r, x); b = Math.max(b, y);
    }
  }
  if (r < 0) throw Error(`no ink in ${src}`);
  return [image.width, image.height, l, t, r + 1 - l, b + 1 - t];
}
const bounds = {};
for (const data of Object.values(manifest.views)) for (const key of OPEN_EYE_GLYPHS) {
  for (const sprite of data.face?.eyes?.[key] || []) if (!bounds[sprite.src]) bounds[sprite.src] = await inkBounds(sprite.src);
}
const inkSize = sprite => { const [iw, ih, , , w, h] = bounds[sprite.src]; return [w / iw * sprite.rect[2], h / ih * sprite.rect[3]]; };
const front = manifest.views.front.face.eyes, relative = {};
for (const key of OPEN_EYE_GLYPHS) relative[key] = front[key].map((sprite, index) => {
  const [w, h] = inkSize(sprite), [nw, nh] = inkSize(front.neutral[index]);
  return [round(w / nw), round(h / nh)];
});
const lines = object => `{\n${Object.keys(object).sort().map(key => `  ${JSON.stringify(key)}: ${JSON.stringify(object[key])}`).join(',\n')}\n}`;
const sorted = object => Object.fromEntries(Object.keys(object).sort().map(key => [key, object[key]]));
const text = `'use strict';
// GENERATED by tools/dango-eye-continuity/footprints.mjs from the raster PNGs; do not edit.
// DANGO_EYE_INK_BOUNDS: [imageWidth, imageHeight, x, y, width, height] of the dark pupil.
// DANGO_EYE_RELATIVE_SCALE: open glyph ink size relative to the front neutral ink, per eye.
const freeze = value => Object.freeze(Object.fromEntries(Object.entries(value)
  .map(([key, entry]) => [key, Object.freeze(Array.isArray(entry[0]) ? entry.map(pair => Object.freeze(pair)) : entry)])));
const DANGO_EYE_INK_BOUNDS = freeze(${lines(bounds)});
const DANGO_EYE_RELATIVE_SCALE = freeze(${lines(relative)});
export { DANGO_EYE_INK_BOUNDS, DANGO_EYE_RELATIVE_SCALE };
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== text) { console.error('dango-eye-footprints.mjs is stale; run node tools/dango-eye-continuity/footprints.mjs'); process.exit(1); }
  console.log('dango eye footprints up to date');
} else { fs.writeFileSync(target, text); console.log(target); }

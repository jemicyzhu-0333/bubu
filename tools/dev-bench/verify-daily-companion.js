'use strict';
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const errors = [];
app.on('browser-window-created', (_, win) => win.webContents.on('console-message', details => {
  if (details.level === 'error') errors.push(details.message);
}));
require('./launch');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const deadline = setTimeout(() => { console.error('native verification timed out'); app.exit(1); }, 60000);
const out = path.resolve(__dirname, '../../dist/daily-companion');
async function run() {
  fs.mkdirSync(out, { recursive: true });
  const popover = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().endsWith('popover.html'));
  const pet = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().endsWith('pet.html'));
  const js = async code => { try { return await popover.webContents.executeJavaScript(code); } catch (error) { console.error('Failed script:', code, errors); throw error; } };
  await pet.webContents.executeJavaScript('window.focuspix.pet_openPanel()');
  await pause(700);
  async function shot(name) { await pause(250); fs.writeFileSync(path.join(out,name+'.png'),(await popover.webContents.capturePage()).toPNG()); }
  await js("window.focuspix.updateSettings({motionMode:'full',stimulationMode:'balanced'})");
  await js("document.getElementById('tabRoutines').click();document.getElementById('btnNewRoutine').click()");
  await js("document.querySelector('[data-kind=custom]').click();document.getElementById('routineCustomLabel').value='植物照料';document.getElementById('routineTitle').value='给绿萝浇水';document.querySelector('[data-frequency=weekly]').click();document.querySelector('[data-weekday=\"2\"]').click();document.querySelector('[data-weekday=\"6\"]').click();document.querySelector('[data-time=\"08:00\"]').click();document.querySelector('[data-time=\"21:00\"]').click()");
  assert.equal(await js("document.getElementById('routineTimes').value"), '08:00,21:00');
  assert.notEqual(await js("getComputedStyle(document.querySelector('[data-kind=custom] [data-icon]'),'::before').content"), 'none');
  assert.ok(await js("document.getElementById('btnAddRoutine').getBoundingClientRect().bottom < innerHeight - 45"));
  await shot('routine-editor');
  await js("document.querySelector('.routine-editor').scrollTop=10000"); await shot('routine-schedule');
  await js("document.getElementById('btnAddRoutine').click()"); await pause(350);
  const routine = await js("window.focuspix.getState().then(s=>s.routines.items.find(r=>r.title==='给绿萝浇水'))");
  assert.equal(routine.customLabel, '植物照料'); assert.deepEqual(routine.schedule.weekdays,[2,6]);
  await js("document.querySelector('#routineManageList [data-act=edit]').click()");
  assert.equal(await js("document.getElementById('routineCustomLabel').value"),'植物照料');
  await js("document.querySelector('[data-time-index=\"0\"][data-part=\"1\"]').value='15';document.querySelector('[data-time-index=\"0\"][data-part=\"1\"]').dispatchEvent(new Event('change',{bubbles:true}));document.getElementById('btnAddRoutine').click()");
  await pause(250);
  assert.equal(await js("window.focuspix.getState().then(s=>s.routines.items.find(r=>r.title==='给绿萝浇水').schedule.timesOfDay[0])"),'08:15');
  await js("document.getElementById('btnRoutineReminders').click()"); await pause(200);
  assert.equal(await js("window.focuspix.getState().then(s=>s.settings.routineRemindersEnabled)"),false);
  await shot('routines');
  await js("document.getElementById('tabCompanion').click();document.getElementById('foodShopPanel').open=true");
  await pause(350);
  assert.equal(await js("document.querySelectorAll('.food-collection-card').length"),10);
  assert.equal(await js("document.querySelectorAll('.food-exchange:not(:disabled)').length"),1);
  assert.ok(await js("document.getElementById('foodShopList').textContent.includes('？？？')"));
  await js("document.querySelector('[data-food-id=berry]').click()"); await pause(250);
  assert.match(await js("document.getElementById('foodShopStatus').textContent"),/已放入/);
  await js("document.getElementById('foodShopPanel').scrollIntoView({block:'start'})"); await shot('food-collection');
  await js("document.getElementById('foodShopPanel').open=false;document.getElementById('bondMilestones').open=true;document.getElementById('journeyPanel').open=true;document.getElementById('bondMilestones').scrollIntoView({block:'start'})");
  assert.equal(await js("document.querySelectorAll('.bond-milestone').length"),3);
  await shot('milestones');
  await js("document.getElementById('tabToday').click();window.focuspix.startPomodoro(null,25)"); await pause(1000);
  assert.match(await js("document.getElementById('headerMiniTime').textContent"),/月.*周.*\d{2}:\d{2}/);
  assert.equal(await js("getComputedStyle(document.querySelector('.pomo-display'),'::before').animationName"),'focus-breathe');
  await shot('focus');
  await js('window.focuspix.pausePomodoro()'); await pause(200);
  assert.equal(await js("getComputedStyle(document.querySelector('.pomo-display'),'::before').animationPlayState"),'paused');
  await js("window.focuspix.updateSettings({motionMode:'reduced'})"); await pause(200);
  assert.equal(await js("getComputedStyle(document.querySelector('.pomo-display'),'::before').animationName"),'none');
  assert.ok(await js('document.documentElement.scrollWidth<=innerWidth'));
  await js("window.focuspix.stopPomodoro()"); await pause(250);
  await js("document.getElementById('tabProgress').click()"); await pause(300);
  await js("{const today=[...document.querySelectorAll('#heatmap .hm-cell')].at(-1);if(today.getAttribute('aria-pressed')!=='true')today.click()}"); await pause(300);
  await js("document.getElementById('timelineDay').scrollIntoView({block:'end'})"); await shot('timeline');
  assert.match(await js("document.getElementById('timelineTrack').textContent"), /自由专注/);
  assert.notEqual(await js("getComputedStyle(document.getElementById('timelineDay')).display"), 'none');
  assert.equal(await js("document.querySelectorAll('.tl-extreme').length"), 2);
  await pet.webContents.executeJavaScript("document.getElementById('feedQuick').click()"); await pause(300);
  assert.ok(await pet.webContents.executeJavaScript("document.querySelector('[data-food=berry]') !== null"));
  await pet.webContents.executeJavaScript("document.querySelector('[data-food=berry]').click()"); await pause(1800);
  fs.writeFileSync(path.join(out,'favorite-food.png'),(await pet.webContents.capturePage()).toPNG());
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ output: out, errors, verified: ['routine create/edit/reminders','food exchange/locks','bond roadmap','clock/pause/reduced motion'] }));
}
app.whenReady().then(() => pause(1600)).then(run).then(() => app.exit(0)).catch(error => { console.error(error.stack); app.exit(1); }).finally(() => clearTimeout(deadline));
